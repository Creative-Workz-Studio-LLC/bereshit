#!/usr/bin/env bash
# =============================================================================
# gen-config-mk.sh — Generate config.mk from build.config.yaml
# =============================================================================
#
# Reads the single source of truth (build.config.yaml) and generates
# a Makefile-consumable config.mk with all project parameters.
#
# Usage:
#   ./build/scripts/gen-config-mk.sh              # Output to stdout
#   ./build/scripts/gen-config-mk.sh > config.mk  # Write to file
#
# Dependencies: yq (Python yq with jq syntax, or Go yq v4+)
#
# Called by: make config
#
# "Write the vision, and make it plain upon tables,
#  that he may run that readeth it." — Habakkuk 2:2
# =============================================================================

set -euo pipefail

# Resolve paths relative to company-docs/ (where Makefile lives)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG="${SCRIPT_DIR}/../build.config.yaml"

if [ ! -f "$CONFIG" ]; then
    echo "Error: build.config.yaml not found at $CONFIG" >&2
    exit 1
fi

if ! command -v yq >/dev/null 2>&1; then
    echo "Error: yq not found. Install with: pip install yq" >&2
    exit 1
fi

# Helper: read a YAML value, return empty string if null
val() {
    local result
    result=$(yq -r "$1 // empty" "$CONFIG" 2>/dev/null)
    echo "$result"
}

# =============================================================================
# Generate config.mk
# =============================================================================

cat <<HEADER
# =============================================================================
# config.mk — AUTO-GENERATED from build.config.yaml
# =============================================================================
# Do not edit this file. Edit build/build.config.yaml and run: make config
#
# Generated: $(date -Iseconds)
# Source:    build/build.config.yaml v$(val '.version')
# =============================================================================

HEADER

# --- Core Tools ---
echo "# --- Core Tools ---"
echo "ADOC_PDF    = $(val '.formats.pdf.command')"
echo "ADOC_HTML   = $(val '.formats.html.command')"
echo ""

# --- Paths ---
echo "# --- Paths ---"
echo "OUTDIR      = $(val '.document.output_dir' | sed 's|^|build/|')"
echo "BOOK_DIR    = $(val '.paths.book_dir')"
echo "PREVIEW_DIR = $(val '.paths.preview_dir')"
echo "THEME_FILE  = $(val '.paths.theme_file')"
echo "ATTRS_FILE  = \$(PREVIEW_DIR)/$(basename "$(val '.paths.shared_attributes')")"
echo ""

# --- Master PDF ---
echo "# --- Master PDF ---"
echo "OUTPUT_STEM = $(val '.document.output_name')"
echo ""

# --- Theme Arguments ---
# Composite value derived from paths and format config
FONT_DIR=$(val '.paths.font_dir')
echo "# --- Theme arguments for standalone section builds ---"
echo "THEME_ARGS = -a pdf-theme=\$(THEME_FILE) \\"
echo "             -a pdf-fontsdir='${FONT_DIR}' \\"
echo "             -a imagesdir=\$(CURDIR)/\$(BOOK_DIR)/00-assets"
echo ""

# --- Flat Scope Definitions ---
echo "# --- Flat Scope Definitions ---"

# Read scope keys dynamically
SCOPE_KEYS=$(yq -r '.scopes | keys | .[]' "$CONFIG" 2>/dev/null)

for key in $SCOPE_KEYS; do
    dir=$(val ".scopes.${key}.directory")
    preview=$(val ".scopes.${key}.preview")
    output=$(val ".scopes.${key}.output")
    name=$(val ".scopes.${key}.name")

    echo ""
    echo "# Scope ${key}: ${name}"
    echo "SCOPE_${key}_DIR     = ${dir}"
    echo "SCOPE_${key}_PREVIEW = ${preview}"
    echo "SCOPE_${key}_OUTPUT  = ${output}"
done
echo ""

# --- Asset Generation Paths ---
echo "# --- Asset Generation Paths ---"
ASSETS_BASE=$(val '.assets.directory')
echo "ASSETS_DIR  = \$(BOOK_DIR)/${ASSETS_BASE}"
echo "ASSETS_PNG  = \$(ASSETS_DIR)/$(val '.assets.figures.png_directory')"
echo "ASSETS_SVG  = \$(ASSETS_DIR)/$(val '.assets.figures.svg_directory')"
echo "ASSETS_GRAY = \$(ASSETS_DIR)/$(val '.assets.figures.grayscale_directory')"
echo "ASSETS_SRC  = \$(ASSETS_DIR)/$(val '.assets.figures.sources')"
echo "MERMAID_CFG = \$(ASSETS_DIR)/$(val '.assets.figures.theme')"
echo "PUPPET_CFG  = \$(ASSETS_DIR)/$(val '.assets.figures.config')/puppeteer-config.json"
echo ""

# --- Brand Colors ---
echo "# --- Brand Colors ---"
echo "BRAND_DEEP_BLUE   = \\$(val '.brand.colors.deep_blue')"
echo "BRAND_MEDIUM_BLUE = \\$(val '.brand.colors.medium_blue')"
echo "BRAND_GOLD        = \\$(val '.brand.colors.gold')"
echo "BRAND_DARK        = \\$(val '.brand.colors.dark')"
echo "BRAND_LIGHT       = \\$(val '.brand.colors.light')"
